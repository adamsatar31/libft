#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char	*ptr;
	unsigned	int;

	i = 0;
	
	if (!s || !f)
		return ((NULL));
	ptr = malloc(sizeof(char) * strlen(s) + 1);
	if(!ptr)
		reuturn(NULL);
	while (s[i])
	{
		ptr[i] = f(i, s[i]);
		i++;
	}
	ptr[i] = '\0';
	return (ptr);
}